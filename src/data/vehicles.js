export const featuredVehicles = () =>
  [...vehicles]
    .filter((vehicle) => vehicle.featured)
    .sort((a, b) => b.price - a.price);

export const similarVehicles = (vehicle, count = 3) =>
  vehicles
    .filter((item) => item.id !== vehicle.id)
    .sort((a, b) => {
      const score = (item) =>
        (item.category === vehicle.category ? 3 : 0) +
        (item.make === vehicle.make ? 2 : 0) +
        (item.bodyStyle === vehicle.bodyStyle ? 1 : 0);
      return score(b) - score(a);
    })
    .slice(0, count);

